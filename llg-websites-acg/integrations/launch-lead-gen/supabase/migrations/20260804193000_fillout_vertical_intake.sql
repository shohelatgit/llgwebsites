create or replace function public.ingest_fillout_submission(
  p_form_id text,
  p_submission jsonb,
  p_payload jsonb,
  p_request_id text,
  p_ingest_token text
)
returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
  v_expected_hash bytea;
  v_submission_id text;
  v_property_key text;
  v_property_id bigint;
  v_service_id bigint;
  v_client_id bigint;
  v_market_id bigint;
  v_test_mode boolean;
  v_event_id bigint;
  v_lead_id bigint;
  v_lead_public_id uuid;
  v_provider_id bigint;
  v_answer record;
  v_question_mapping_id bigint;
  v_source_category text;
begin
  select secret_hash into v_expected_hash
  from private.integration_secrets
  where secret_key = 'fillout_ingest';

  if v_expected_hash is null
    or extensions.digest(coalesce(p_ingest_token, ''), 'sha256') <> v_expected_hash then
    raise exception 'unauthorized intake request' using errcode = '28000';
  end if;

  if jsonb_typeof(p_submission) <> 'object' or jsonb_typeof(p_payload) <> 'object' then
    raise exception 'invalid submission payload' using errcode = '22023';
  end if;

  v_submission_id := nullif(btrim(p_submission->>'submissionId'), '');
  v_property_key := nullif(btrim(p_submission->>'propertyKey'), '');
  if v_submission_id is null or v_property_key is null then
    raise exception 'missing submission identity' using errcode = '22023';
  end if;

  select sm.service_id
  into v_service_id
  from public.source_mappings sm
  where sm.platform = 'fillout'
    and sm.external_type = 'form_template'
    and sm.external_id = p_form_id
    and sm.is_active
    and sm.service_id is not null;

  if v_service_id is null then
    raise exception 'unmapped fillout form' using errcode = 'P0002';
  end if;

  select p.id, p.client_id, p.market_id, coalesce(pc.test_mode, true)
  into v_property_id, v_client_id, v_market_id, v_test_mode
  from public.properties p
  left join public.property_configurations pc on pc.property_id = p.id
  where p.property_key = v_property_key;

  if v_property_id is null then
    raise exception 'unknown property key' using errcode = 'P0002';
  end if;

  if not exists (
    select 1
    from public.property_services ps
    where ps.property_id = v_property_id
      and ps.service_id = v_service_id
      and ps.is_active
      and ps.accepting_leads
  ) then
    raise exception 'form does not match property service' using errcode = '22023';
  end if;

  insert into public.webhook_events (
    source_system, event_id, event_type, status, payload, received_at, attempt_count
  )
  values (
    'fillout', v_submission_id, 'form_submission', 'processing', p_payload, now(), 1
  )
  on conflict (source_system, event_id) do nothing
  returning id into v_event_id;

  if v_event_id is null then
    select l.id, l.public_id, l.property_id, l.service_id
    into v_lead_id, v_lead_public_id, v_property_id, v_service_id
    from public.leads l
    where l.source_system = 'fillout' and l.source_record_id = v_submission_id;

    if v_lead_id is null then
      raise exception 'duplicate event has no lead' using errcode = 'P0002';
    end if;

    return jsonb_build_object(
      'accepted', true,
      'duplicate', true,
      'lead_id', v_lead_id,
      'lead_public_id', v_lead_public_id,
      'property_id', v_property_id,
      'service_id', v_service_id,
      'test_mode', v_test_mode
    );
  end if;

  v_source_category := case
    when p_submission#>>'{attribution,source_category}' in ('paid','organic','referral','direct','partner','offline','unknown')
      then p_submission#>>'{attribution,source_category}'
    else 'unknown'
  end;

  insert into public.leads (
    ingestion_key, source_system, source_record_id, source_event_id,
    property_id, market_id, service_id, received_at, occurred_at,
    first_name, last_name, full_name, phone, normalized_phone, email, normalized_email,
    address_line_1, address_line_2, city, state_region, postal_code,
    lead_source, source_category, communication_channel, conversion_source,
    utm_source, utm_medium, utm_campaign, utm_content, utm_term, utm_id,
    campaign_id, campaign_name, ad_group_id, ad_group_name, ad_id, ad_name,
    keyword, match_type, gclid, gbraid, wbraid, fbclid, msclkid, rdt_cid, ttclid, li_fat_id,
    landing_page_url, referrer_url, visitor_id, session_id, clarity_session_id,
    fillout_submission_id, status, qualification_status, is_billable,
    consent_to_contact, consent_text, metadata
  ) values (
    'fillout:' || v_submission_id, 'fillout', v_submission_id, v_event_id,
    v_property_id, v_market_id, v_service_id, now(),
    coalesce((p_submission->>'submissionTime')::timestamptz, now()),
    nullif(p_submission->>'firstName',''), nullif(p_submission->>'lastName',''), nullif(p_submission->>'fullName',''),
    nullif(p_submission->>'phone',''), nullif(p_submission->>'phone',''),
    nullif(lower(p_submission->>'email'),''), nullif(lower(p_submission->>'email'),''),
    nullif(p_submission->>'addressLine1',''), nullif(p_submission->>'addressLine2',''),
    nullif(p_submission->>'city',''), nullif(p_submission->>'stateRegion',''), nullif(p_submission->>'postalCode',''),
    coalesce(nullif(p_submission#>>'{attribution,utm_source}',''), 'Website Form'),
    v_source_category, 'website_form', 'Fillout',
    nullif(p_submission#>>'{attribution,utm_source}',''), nullif(p_submission#>>'{attribution,utm_medium}',''),
    nullif(p_submission#>>'{attribution,utm_campaign}',''), nullif(p_submission#>>'{attribution,utm_content}',''),
    nullif(p_submission#>>'{attribution,utm_term}',''), nullif(p_submission#>>'{attribution,utm_id}',''),
    nullif(p_submission#>>'{attribution,campaign_id}',''), nullif(p_submission#>>'{attribution,campaign_name}',''),
    nullif(p_submission#>>'{attribution,ad_group_id}',''), nullif(p_submission#>>'{attribution,ad_group_name}',''),
    nullif(p_submission#>>'{attribution,ad_id}',''), nullif(p_submission#>>'{attribution,ad_name}',''),
    nullif(p_submission#>>'{attribution,keyword}',''), nullif(p_submission#>>'{attribution,match_type}',''),
    nullif(p_submission#>>'{attribution,gclid}',''), nullif(p_submission#>>'{attribution,gbraid}',''),
    nullif(p_submission#>>'{attribution,wbraid}',''), nullif(p_submission#>>'{attribution,fbclid}',''),
    nullif(p_submission#>>'{attribution,msclkid}',''), nullif(p_submission#>>'{attribution,rdt_cid}',''),
    nullif(p_submission#>>'{attribution,ttclid}',''), nullif(p_submission#>>'{attribution,li_fat_id}',''),
    nullif(p_submission#>>'{attribution,landing_page_url}',''), nullif(p_submission#>>'{attribution,referrer_url}',''),
    nullif(p_submission#>>'{attribution,visitor_id}',''), nullif(p_submission#>>'{attribution,session_id}',''),
    nullif(p_submission#>>'{attribution,clarity_session_id}',''),
    v_submission_id,
    case when v_test_mode then 'validating' else 'new' end,
    case when v_test_mode then 'needs_review' else 'unreviewed' end,
    case when v_test_mode then false else null end,
    coalesce((p_submission->>'consentGranted')::boolean, false),
    nullif(p_submission->>'consentText',''),
    jsonb_build_object(
      'request_id', p_request_id,
      'test_mode', v_test_mode,
      'fillout_form_id', p_form_id,
      'consent_version', p_submission->>'consentVersion',
      'message', p_submission->>'message',
      'answers', coalesce(p_submission->'answers', '{}'::jsonb),
      'questions', coalesce(p_submission->'questions', '[]'::jsonb),
      'url_parameters', coalesce(p_submission->'urlParameters', '[]'::jsonb)
    )
  )
  returning id, public_id into v_lead_id, v_lead_public_id;

  select ip.id into v_provider_id
  from public.integration_providers ip
  where ip.provider_key = 'fillout' and ip.is_active;

  insert into public.lead_interactions (
    lead_id, property_id, provider_id, source_event_id, interaction_type,
    channel, direction, status, summary, content, occurred_at, metadata
  ) values (
    v_lead_id, v_property_id, v_provider_id, v_submission_id, 'form_submission',
    'web', 'inbound', 'received', 'Website quote request submitted',
    nullif(p_submission->>'message',''),
    coalesce((p_submission->>'submissionTime')::timestamptz, now()),
    jsonb_build_object('fillout_form_id', p_form_id, 'request_id', p_request_id, 'test_mode', v_test_mode)
  );

  insert into public.lead_consent_events (
    lead_id, property_id, consent_type, consent_status, disclosure_text,
    capture_source, occurred_at, metadata
  ) values (
    v_lead_id, v_property_id, 'contact',
    case when coalesce((p_submission->>'consentGranted')::boolean, false) then 'granted' else 'denied' end,
    nullif(p_submission->>'consentText',''), 'fillout',
    coalesce((p_submission->>'submissionTime')::timestamptz, now()),
    jsonb_build_object('consent_version', p_submission->>'consentVersion', 'fillout_submission_id', v_submission_id)
  );

  if jsonb_typeof(p_submission->'answers') = 'object' then
    for v_answer in select key, value from jsonb_each(p_submission->'answers')
    loop
      select psq.id into v_question_mapping_id
      from public.property_service_questions psq
      join public.qualification_questions q on q.id = psq.question_id
      where psq.property_id = v_property_id
        and psq.service_id = v_service_id
        and psq.is_active
        and q.question_key = v_answer.key;

      if v_question_mapping_id is not null then
        insert into public.lead_qualification_answers (
          lead_id, property_service_question_id, answer_text, answer_number,
          answer_boolean, answer_json, answered_via, metadata
        ) values (
          v_lead_id,
          v_question_mapping_id,
          case when jsonb_typeof(v_answer.value) = 'string' then v_answer.value #>> '{}' else null end,
          case when jsonb_typeof(v_answer.value) = 'number' then (v_answer.value #>> '{}')::numeric else null end,
          case when jsonb_typeof(v_answer.value) = 'boolean' then (v_answer.value #>> '{}')::boolean else null end,
          v_answer.value,
          'form',
          jsonb_build_object('fillout_form_id', p_form_id, 'fillout_submission_id', v_submission_id)
        );
      end if;
    end loop;
  end if;

  update public.webhook_events
  set status = 'processed', processed_at = now()
  where id = v_event_id;

  return jsonb_build_object(
    'accepted', true,
    'duplicate', false,
    'lead_id', v_lead_id,
    'lead_public_id', v_lead_public_id,
    'property_id', v_property_id,
    'service_id', v_service_id,
    'test_mode', v_test_mode
  );
end;
$$;

revoke all on function public.ingest_fillout_submission(text, jsonb, jsonb, text, text) from public;
grant execute on function public.ingest_fillout_submission(text, jsonb, jsonb, text, text) to anon, service_role;

