create schema if not exists private;

create table if not exists private.integration_secrets (
  secret_key text primary key,
  secret_hash bytea not null,
  updated_at timestamptz not null default now()
);

revoke all on schema private from public, anon, authenticated;
revoke all on all tables in schema private from public, anon, authenticated;

create table if not exists public.form_templates (
  id bigint generated by default as identity primary key,
  template_key text not null unique,
  provider_key text not null default 'fillout',
  fillout_form_id text unique,
  service_id bigint not null references public.services(id) on delete restrict,
  name text not null,
  status text not null default 'draft' check (status in ('draft', 'testing', 'active', 'paused', 'retired')),
  schema_version integer not null default 1 check (schema_version > 0),
  qualification_schema jsonb not null default '[]'::jsonb check (jsonb_typeof(qualification_schema) = 'array'),
  attribution_parameters text[] not null default array[]::text[],
  webhook_enabled boolean not null default false,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists form_templates_service_id_idx on public.form_templates(service_id);

create table if not exists public.property_form_templates (
  property_id bigint not null references public.properties(id) on delete cascade,
  form_template_id bigint not null references public.form_templates(id) on delete cascade,
  is_primary boolean not null default true,
  is_active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (property_id, form_template_id)
);

create index if not exists property_form_templates_form_template_id_idx on public.property_form_templates(form_template_id);

alter table public.form_templates enable row level security;
alter table public.property_form_templates enable row level security;

