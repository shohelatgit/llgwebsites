create table public.sms_qualification_flows (
  property_id bigint primary key references public.properties(id) on delete cascade,
  sending_provider_id bigint not null references public.integration_providers(id),
  sending_phone_e164 text not null check (sending_phone_e164 ~ '^\+[1-9][0-9]{7,14}$'),
  status text not null default 'draft'
    check (status in ('draft', 'testing', 'active', 'paused', 'retired')),
  intro_message text not null,
  questions jsonb not null check (jsonb_typeof(questions) = 'array'),
  completion_message text not null,
  settings jsonb not null default '{}'::jsonb check (jsonb_typeof(settings) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.sms_qualification_sessions (
  id bigint generated by default as identity primary key,
  property_id bigint not null references public.properties(id),
  lead_id bigint references public.leads(id),
  contact_phone_e164 text not null check (contact_phone_e164 ~ '^\+[1-9][0-9]{7,14}$'),
  sending_provider_id bigint not null references public.integration_providers(id),
  sending_phone_e164 text not null check (sending_phone_e164 ~ '^\+[1-9][0-9]{7,14}$'),
  status text not null default 'active'
    check (status in ('active', 'completed', 'opted_out', 'paused', 'expired')),
  current_step integer not null default 0 check (current_step >= 0),
  answers jsonb not null default '{}'::jsonb check (jsonb_typeof(answers) = 'object'),
  last_inbound_provider_id bigint references public.integration_providers(id),
  last_inbound_message_id text,
  last_reply_text text,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  last_activity_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index sms_qualification_sessions_one_active_idx
  on public.sms_qualification_sessions (property_id, contact_phone_e164)
  where status = 'active';
create index sms_qualification_sessions_lead_idx
  on public.sms_qualification_sessions (lead_id, last_activity_at desc)
  where lead_id is not null;
create index sms_qualification_sessions_contact_idx
  on public.sms_qualification_sessions (contact_phone_e164, last_activity_at desc);

