create table if not exists public.sms_number_assignments (
  id bigint generated by default as identity primary key,
  provider_id bigint not null references public.integration_providers(id),
  property_id bigint not null references public.properties(id),
  phone_e164 text not null,
  external_number_id text,
  label text,
  routing_status text not null default 'inventory'
    check (routing_status in ('inventory', 'testing', 'active', 'paused', 'retired')),
  is_primary boolean not null default false,
  capabilities jsonb not null default '{"sms":true,"mms":false}'::jsonb
    check (jsonb_typeof(capabilities) = 'object'),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider_id, phone_e164),
  check (phone_e164 ~ '^\+[1-9][0-9]{7,14}$')
);

create index if not exists sms_number_assignments_property_status_idx
  on public.sms_number_assignments (property_id, routing_status);

create unique index if not exists sms_number_assignments_one_primary_idx
  on public.sms_number_assignments (property_id)
  where is_primary and routing_status in ('testing', 'active');

create table if not exists public.sms_messages (
  id bigint generated by default as identity primary key,
  provider_id bigint not null references public.integration_providers(id),
  external_message_id text not null,
  property_id bigint references public.properties(id),
  lead_id bigint references public.leads(id),
  number_assignment_id bigint references public.sms_number_assignments(id),
  direction text not null check (direction in ('inbound', 'outbound')),
  from_phone_e164 text,
  to_phone_e164 text,
  status text not null default 'received',
  message_body text,
  occurred_at timestamptz not null default now(),
  delivered_at timestamptz,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider_id, external_message_id)
);

create index if not exists sms_messages_property_occurred_idx
  on public.sms_messages (property_id, occurred_at desc);
create index if not exists sms_messages_lead_occurred_idx
  on public.sms_messages (lead_id, occurred_at desc)
  where lead_id is not null;
create index if not exists sms_messages_contact_lookup_idx
  on public.sms_messages (property_id, from_phone_e164, occurred_at desc)
  where direction = 'inbound';

