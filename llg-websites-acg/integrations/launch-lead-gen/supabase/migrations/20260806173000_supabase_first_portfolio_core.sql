create or replace function public.ingest_provider_event(
  p_event jsonb,
  p_payload jsonb,
  p_request_id text,
  p_ingest_token text
)
returns jsonb
language plpgsql
security definer
set search_path = public, private, extensions, pg_temp
as $$
declare
  v_provider text := lower(nullif(btrim(p_event->>'provider'), ''));
  v_provider_event_id text := nullif(btrim(p_event->>'provider_event_id'), '');
  v_event_type text := coalesce(nullif(btrim(p_event->>'event_type'), ''), 'conversion');
  v_idempotency_key text := coalesce(nullif(btrim(p_event->>'idempotency_key'), ''), v_provider || ':' || v_provider_event_id);
  v_event_uid text;
  v_property_key text := nullif(btrim(p_event->>'property_key'), '');
  v_property_id bigint;
  v_mapping_count integer := 0;
  v_mapping_status text := 'unmapped';
  v_mapping_evidence jsonb := '{}'::jsonb;
  v_channel text := lower(coalesce(nullif(p_event->>'conversion_channel',''), 'other'));
  v_gate_channel text;
  v_gate_status text;
  v_acquisition text := lower(coalesce(nullif(p_event->>'acquisition_source',''), 'unknown'));
  v_confidence text := lower(coalesce(nullif(p_event->>'acquisition_confidence',''), 'unknown'));
  v_test_mode boolean := coalesce((p_event->>'test_mode')::boolean, true);
  v_webhook_id bigint;
  v_normalized_id bigint;
  v_lead_id bigint;
  v_lead_public_id uuid;
  v_duplicate boolean := false;
  v_market_id bigint;
  v_service_id bigint;
  v_provider_id bigint;
  v_occurred_at timestamptz := coalesce(nullif(p_event->>'occurred_at','')::timestamptz, now());
  v_contact jsonb := coalesce(p_event->'contact', '{}'::jsonb);
  v_consent jsonb := coalesce(p_event->'consent', '{}'::jsonb);
  v_service jsonb := coalesce(p_event->'service', '{}'::jsonb);
  v_attribution jsonb := coalesce(p_event->'attribution', '{}'::jsonb);
  v_correlation jsonb := coalesce(p_event->'correlation_ids', '{}'::jsonb);
begin
  perform private.assert_portfolio_ingest_token(p_ingest_token);
  if jsonb_typeof(p_event) <> 'object' or jsonb_typeof(p_payload) <> 'object' then
    raise exception 'event and payload must be objects' using errcode = '22023';
  end if;
  if v_provider is null or v_provider_event_id is null then
    raise exception 'provider and provider_event_id are required' using errcode = '22023';
  end if;
  if v_channel not in ('website_form','phone_call','sms','email','other') then
    raise exception 'invalid conversion channel' using errcode = '22023';
  end if;
  if v_confidence not in ('confirmed','explicit','inferred','ambiguous','unverified','unknown') then
    v_confidence := 'unknown';
  end if;
  v_event_uid := v_provider || ':' || v_provider_event_id;

  insert into public.webhook_events(source_system,event_id,event_type,status,payload,received_at,attempt_count)
  values (v_provider,v_provider_event_id,v_event_type,'processing',p_payload,now(),1)
  on conflict (source_system,event_id) do update
  set payload=excluded.payload,status='processing',error_message=null,
      attempt_count=public.webhook_events.attempt_count+1
  returning id into v_webhook_id;

  if v_property_key is not null then
    select id into v_property_id from public.properties where property_key = v_property_key;
    if v_property_id is not null then
      v_mapping_status := 'matched';
      v_mapping_evidence := jsonb_build_object('method','property_key','property_key',v_property_key);
    end if;
  end if;

  if v_property_id is null and jsonb_typeof(p_event->'mapping_keys') = 'array' then
    with supplied as (
      select lower(k->>'platform') platform, lower(k->>'external_type') external_type, k->>'external_id' external_id
      from jsonb_array_elements(p_event->'mapping_keys') k
      where nullif(k->>'platform','') is not null and nullif(k->>'external_type','') is not null and nullif(k->>'external_id','') is not null
    ), matches as (
      select distinct sm.property_id, sm.platform, sm.external_type, sm.external_id
      from supplied s join public.source_mappings sm
        on lower(sm.platform)=s.platform and lower(sm.external_type)=s.external_type and sm.external_id=s.external_id
      where sm.is_active and sm.mapping_status='verified' and sm.property_id is not null
    )
    select count(distinct property_id), min(property_id),
      jsonb_build_object('method','source_mappings','matches',coalesce(jsonb_agg(jsonb_build_object('platform',platform,'external_type',external_type,'external_id',external_id)), '[]'::jsonb))
    into v_mapping_count, v_property_id, v_mapping_evidence from matches;
    if v_mapping_count = 1 then v_mapping_status := 'matched';
    elsif v_mapping_count > 1 then v_property_id := null; v_mapping_status := 'ambiguous';
    else v_property_id := null; v_mapping_status := 'unmapped';
    end if;
  end if;

  if v_property_id is not null then
    select p.market_id, coalesce(pc.test_mode,true) into v_market_id, v_test_mode
    from public.properties p left join public.property_configurations pc on pc.property_id=p.id
    where p.id=v_property_id;
    v_test_mode := coalesce((p_event->>'test_mode')::boolean, v_test_mode, true);
    if v_channel in ('website_form','phone_call') then v_gate_channel := v_channel;
    elsif v_acquisition='google_ads' then v_gate_channel := 'google_ads';
    elsif v_acquisition='meta_ads' then v_gate_channel := 'meta_ads';
    else v_gate_channel := v_channel; end if;
    select status into v_gate_status
    from public.property_channel_readiness
    where property_id=v_property_id and channel=v_gate_channel;
    if not v_test_mode and coalesce(v_gate_status,'blocked') <> 'live' then
      v_mapping_status := 'blocked';
    end if;
  end if;

  if v_acquisition='google_ads'
    and coalesce(v_attribution->>'gclid','')=''
    and coalesce(v_attribution->>'gbraid','')=''
    and coalesce(v_attribution->>'wbraid','')=''
    and not (
      lower(coalesce(v_attribution->>'utm_source','')) in ('google','adwords')
      and lower(coalesce(v_attribution->>'utm_medium','')) in ('cpc','ppc','paid','paid_search')
    ) then
    v_acquisition := 'google_unverified';
    v_confidence := 'unverified';
  end if;

  insert into public.normalized_provider_events(
    event_uid,idempotency_key,provider,provider_event_id,event_type,property_id,mapping_status,mapping_evidence,
    acquisition_source,acquisition_confidence,conversion_channel,campaign_id,campaign_name,ad_group_id,ad_group_name,
    ad_id,ad_name,keyword,utm_source,utm_medium,utm_campaign,utm_content,utm_term,gclid,gbraid,wbraid,fbclid,
    landing_page_url,referrer_url,visitor_id,session_id,contact,consent,service,qualification,occurred_at,test_mode,
    processing_status,raw_webhook_event_id,correlation_ids,metadata,updated_at
  ) values (
    v_event_uid,v_idempotency_key,v_provider,v_provider_event_id,v_event_type,v_property_id,v_mapping_status,v_mapping_evidence,
    v_acquisition,v_confidence,v_channel,nullif(v_attribution->>'campaign_id',''),nullif(v_attribution->>'campaign_name',''),
    nullif(v_attribution->>'ad_group_id',''),nullif(v_attribution->>'ad_group_name',''),nullif(v_attribution->>'ad_id',''),
    nullif(v_attribution->>'ad_name',''),nullif(v_attribution->>'keyword',''),nullif(v_attribution->>'utm_source',''),
    nullif(v_attribution->>'utm_medium',''),nullif(v_attribution->>'utm_campaign',''),nullif(v_attribution->>'utm_content',''),
    nullif(v_attribution->>'utm_term',''),nullif(v_attribution->>'gclid',''),nullif(v_attribution->>'gbraid',''),
    nullif(v_attribution->>'wbraid',''),nullif(v_attribution->>'fbclid',''),nullif(v_attribution->>'landing_page_url',''),
    nullif(v_attribution->>'referrer_url',''),nullif(v_attribution->>'visitor_id',''),nullif(v_attribution->>'session_id',''),
    v_contact,v_consent,v_service,coalesce(p_event->'qualification','{}'::jsonb),v_occurred_at,v_test_mode,
    case when v_mapping_status='matched' then 'received' when v_mapping_status='blocked' then 'blocked' else 'unmapped' end,v_webhook_id,v_correlation,
    jsonb_build_object('request_id',p_request_id,'contract_version','2026-08-06'),now()
  )
  on conflict (provider,provider_event_id) do update
  set mapping_status=excluded.mapping_status,mapping_evidence=excluded.mapping_evidence,property_id=coalesce(excluded.property_id,public.normalized_provider_events.property_id),
      contact=excluded.contact,consent=excluded.consent,service=excluded.service,qualification=excluded.qualification,
      correlation_ids=public.normalized_provider_events.correlation_ids||excluded.correlation_ids,updated_at=now()
  returning id, lead_id into v_normalized_id, v_lead_id;

  if v_lead_id is not null then
    v_duplicate := true;
    update public.normalized_provider_events set processing_status='duplicate',updated_at=now() where id=v_normalized_id;
    update public.webhook_events set status='processed',processed_at=now() where id=v_webhook_id;
    return jsonb_build_object('accepted',true,'duplicate',true,'lead_id',v_lead_id,'property_id',v_property_id,'mapping_status',v_mapping_status,'test_mode',v_test_mode);
  end if;
  if v_mapping_status <> 'matched' then
    update public.webhook_events set status='processed',processed_at=now(),error_message='retained:'||v_mapping_status where id=v_webhook_id;
    return jsonb_build_object('accepted',false,'duplicate',false,'lead_id',null,'property_id',v_property_id,'mapping_status',v_mapping_status,'test_mode',v_test_mode);
  end if;

  if nullif(v_service->>'service_id','') ~ '^[0-9]+$' then v_service_id := (v_service->>'service_id')::bigint; end if;
  if v_service_id is null then
    select ps.service_id into v_service_id from public.property_services ps
    where ps.property_id=v_property_id and ps.is_active and ps.accepting_leads
    order by ps.is_primary desc,ps.sort_order,ps.service_id limit 1;
  end if;
  select id into v_lead_id from public.leads where ingestion_key=v_idempotency_key;
  if v_lead_id is null then
    insert into public.leads(
      ingestion_key,source_system,source_record_id,source_event_id,property_id,market_id,service_id,received_at,occurred_at,
      first_name,last_name,full_name,phone,normalized_phone,email,normalized_email,address_line_1,address_line_2,city,state_region,postal_code,
      lead_source,source_category,communication_channel,conversion_source,utm_source,utm_medium,utm_campaign,utm_content,utm_term,
      campaign_id,campaign_name,ad_group_id,ad_group_name,ad_id,ad_name,keyword,gclid,gbraid,wbraid,fbclid,landing_page_url,referrer_url,
      visitor_id,session_id,fillout_submission_id,callrail_call_id,status,qualification_status,is_billable,consent_to_contact,consent_text,metadata
    ) values (
      v_idempotency_key,v_provider,v_provider_event_id,v_webhook_id,v_property_id,v_market_id,v_service_id,now(),v_occurred_at,
      nullif(v_contact->>'first_name',''),nullif(v_contact->>'last_name',''),nullif(v_contact->>'full_name',''),
      nullif(v_contact->>'phone',''),nullif(v_contact->>'normalized_phone',''),nullif(lower(v_contact->>'email'),''),nullif(lower(v_contact->>'normalized_email'),''),
      nullif(v_contact->>'address_line_1',''),nullif(v_contact->>'address_line_2',''),nullif(v_contact->>'city',''),nullif(v_contact->>'state_region',''),nullif(v_contact->>'postal_code',''),
      v_acquisition,v_acquisition,v_channel,v_provider,nullif(v_attribution->>'utm_source',''),nullif(v_attribution->>'utm_medium',''),
      nullif(v_attribution->>'utm_campaign',''),nullif(v_attribution->>'utm_content',''),nullif(v_attribution->>'utm_term',''),
      nullif(v_attribution->>'campaign_id',''),nullif(v_attribution->>'campaign_name',''),nullif(v_attribution->>'ad_group_id',''),
      nullif(v_attribution->>'ad_group_name',''),nullif(v_attribution->>'ad_id',''),nullif(v_attribution->>'ad_name',''),nullif(v_attribution->>'keyword',''),
      nullif(v_attribution->>'gclid',''),nullif(v_attribution->>'gbraid',''),nullif(v_attribution->>'wbraid',''),nullif(v_attribution->>'fbclid',''),
      nullif(v_attribution->>'landing_page_url',''),nullif(v_attribution->>'referrer_url',''),nullif(v_attribution->>'visitor_id',''),nullif(v_attribution->>'session_id',''),
      case when v_provider='fillout' then v_provider_event_id else null end,case when v_provider='callrail' then v_provider_event_id else null end,
      'validating','needs_review',false,coalesce((v_consent->>'granted')::boolean,false),nullif(v_consent->>'text',''),
      jsonb_build_object('test_mode',v_test_mode,'supabase_first_capture',true,'normalized_provider_event_id',v_normalized_id,
        'site_attribution_confidence','direct','acquisition_confidence',v_confidence,'mapping_evidence',v_mapping_evidence,
