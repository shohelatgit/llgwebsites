create or replace function public.upsert_portfolio_ad_metric(p_metric jsonb,p_ingest_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, private, extensions, pg_temp
as $$
declare
  v_property_id bigint;
  v_mapping_count integer;
  v_id bigint;
  v_inserted boolean;
begin
  perform private.assert_portfolio_ingest_token(p_ingest_token);
  if jsonb_typeof(p_metric) <> 'object' then raise exception 'metric must be an object' using errcode='22023'; end if;
  with keys as (
    select lower(k->>'platform') platform,lower(k->>'external_type') external_type,k->>'external_id' external_id
    from jsonb_array_elements(coalesce(p_metric->'mapping_keys','[]'::jsonb)) k
  ), matches as (
    select distinct sm.property_id from keys k join public.source_mappings sm
      on lower(sm.platform)=k.platform and lower(sm.external_type)=k.external_type and sm.external_id=k.external_id
    where sm.is_active and sm.mapping_status='verified' and sm.property_id is not null
  ) select count(*),min(property_id) into v_mapping_count,v_property_id from matches;
  if v_mapping_count <> 1 then v_property_id := null; end if;
  select id into v_id from public.daily_ad_metrics
  where metric_date=(p_metric->>'metric_date')::date and platform=p_metric->>'platform' and account_id=p_metric->>'account_id'
    and campaign_id=p_metric->>'campaign_id' and coalesce(ad_group_id,'')=coalesce(p_metric->>'ad_group_id','')
    and coalesce(ad_id,'')=coalesce(p_metric->>'ad_id','') and coalesce(property_id,0)=coalesce(v_property_id,0);
  v_inserted := v_id is null;
  insert into public.daily_ad_metrics(metric_date,platform,account_id,account_name,campaign_id,campaign_name,ad_group_id,ad_group_name,ad_id,ad_name,
    client_id,property_id,impressions,clicks,spend,conversions,conversion_value,currency_code,metadata,imported_at)
  values ((p_metric->>'metric_date')::date,p_metric->>'platform',p_metric->>'account_id',nullif(p_metric->>'account_name',''),p_metric->>'campaign_id',
    nullif(p_metric->>'campaign_name',''),nullif(p_metric->>'ad_group_id',''),nullif(p_metric->>'ad_group_name',''),nullif(p_metric->>'ad_id',''),nullif(p_metric->>'ad_name',''),
    null,v_property_id,coalesce((p_metric->>'impressions')::bigint,0),coalesce((p_metric->>'clicks')::bigint,0),coalesce((p_metric->>'spend')::numeric,0),
    coalesce((p_metric->>'conversions')::numeric,0),coalesce((p_metric->>'conversion_value')::numeric,0),coalesce(nullif(p_metric->>'currency_code',''),'USD'),
    jsonb_build_object('mapping_status',case when v_property_id is null then 'unmapped' else 'matched' end,'mapping_keys',coalesce(p_metric->'mapping_keys','[]'::jsonb)),now())
  on conflict (metric_date,platform,account_id,campaign_id,(coalesce(ad_group_id,'')),(coalesce(ad_id,'')),(coalesce(property_id,0))) do update
  set account_name=excluded.account_name,campaign_name=excluded.campaign_name,ad_group_name=excluded.ad_group_name,ad_name=excluded.ad_name,
      impressions=excluded.impressions,clicks=excluded.clicks,spend=excluded.spend,conversions=excluded.conversions,
      conversion_value=excluded.conversion_value,currency_code=excluded.currency_code,metadata=excluded.metadata,imported_at=now()
  returning id into v_id;
  return jsonb_build_object('id',v_id,'inserted',v_inserted,'property_id',v_property_id,'unmapped',v_property_id is null);
end;
$$;

