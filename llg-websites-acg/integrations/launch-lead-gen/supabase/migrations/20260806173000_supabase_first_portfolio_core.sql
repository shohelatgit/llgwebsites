  values (v_lead_id,v_property_id,v_provider_id,v_provider_event_id,nullif(v_correlation->>'conversation_id',''),
    case when v_channel='phone_call' then 'call' else 'form_submission' end,v_channel,'inbound','received',
    nullif(p_event->>'summary',''),nullif(p_event->>'message',''),v_occurred_at,
    jsonb_build_object('normalized_provider_event_id',v_normalized_id,'test_mode',v_test_mode,'acquisition_source',v_acquisition))
  on conflict do nothing;

  insert into public.lead_attribution_touches(lead_id,touch_order,touch_type,occurred_at,source,medium,campaign,campaign_id,ad_group_id,ad_id,keyword,landing_page_url,referrer_url,gclid,gbraid,wbraid,fbclid,visitor_id,session_id,metadata)
  values (v_lead_id,1,'last_touch',v_occurred_at,v_acquisition,nullif(v_attribution->>'utm_medium',''),nullif(v_attribution->>'utm_campaign',''),
    nullif(v_attribution->>'campaign_id',''),nullif(v_attribution->>'ad_group_id',''),nullif(v_attribution->>'ad_id',''),nullif(v_attribution->>'keyword',''),
    nullif(v_attribution->>'landing_page_url',''),nullif(v_attribution->>'referrer_url',''),nullif(v_attribution->>'gclid',''),nullif(v_attribution->>'gbraid',''),
    nullif(v_attribution->>'wbraid',''),nullif(v_attribution->>'fbclid',''),nullif(v_attribution->>'visitor_id',''),nullif(v_attribution->>'session_id',''),
    jsonb_build_object('confidence',v_confidence,'normalized_provider_event_id',v_normalized_id))
  on conflict (lead_id,touch_order) do nothing;

  update public.normalized_provider_events set lead_id=v_lead_id,processing_status=case when v_duplicate then 'duplicate' else 'processed' end,updated_at=now() where id=v_normalized_id;
  update public.webhook_events set status='processed',processed_at=now() where id=v_webhook_id;
  update public.property_channel_readiness set last_tested_at=case when v_test_mode then now() else last_tested_at end,updated_at=now()
  where property_id=v_property_id and channel in (v_channel,case when v_acquisition in ('google_ads','meta_ads') then v_acquisition else v_channel end);
  return jsonb_build_object('accepted',true,'duplicate',v_duplicate,'lead_id',v_lead_id,'lead_public_id',v_lead_public_id,
    'property_id',v_property_id,'mapping_status',v_mapping_status,'test_mode',v_test_mode,'normalized_event_id',v_normalized_id);
exception when others then
  if v_webhook_id is not null then update public.webhook_events set status='failed',error_message=sqlerrm where id=v_webhook_id; end if;
  if v_normalized_id is not null then update public.normalized_provider_events set processing_status='failed',error_message=sqlerrm,updated_at=now() where id=v_normalized_id; end if;
  raise;
end;
$$;

