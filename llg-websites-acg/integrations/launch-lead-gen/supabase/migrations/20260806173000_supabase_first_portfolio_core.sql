create or replace function private.assert_portfolio_ingest_token(p_token text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_expected_hash text;
begin
  select secret_hash into v_expected_hash
  from private.integration_secrets
  where secret_key = 'fillout_ingest';
  if v_expected_hash is null
    or extensions.digest(coalesce(p_token, ''), 'sha256') <> v_expected_hash then
    raise exception 'unauthorized intake request' using errcode = '28000';
  end if;
end;
$$;

revoke all on function private.assert_portfolio_ingest_token(text) from public, anon, authenticated;

create or replace function private.enforce_internal_lead_safety()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_delivery_enabled boolean := false;
begin
  select delivery_enabled into v_delivery_enabled
  from public.portfolio_controls where control_key = 'lead_operations';
  if not coalesce(v_delivery_enabled, false) and tg_op = 'INSERT' then
    new.assigned_client_id := null;
    new.is_billable := false;
    new.status := 'validating';
    new.qualification_status := 'needs_review';
    new.routed_at := null;
  end if;
  return new;
end;
$$;

drop trigger if exists leads_internal_safety_before_insert on public.leads;
create trigger leads_internal_safety_before_insert
before insert on public.leads
for each row execute function private.enforce_internal_lead_safety();

