create or replace function public.prepare_bland_call_correlation(p_payload jsonb,p_ingest_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, private, extensions, pg_temp
as $$
declare v_callrail_id text; v_phone text; v_started timestamptz; v_lead public.leads; v_result jsonb := p_payload;
begin
  perform private.assert_portfolio_ingest_token(p_ingest_token);
  v_callrail_id := coalesce(nullif(p_payload->>'callrail_call_id',''),nullif(p_payload#>>'{metadata,callrail_call_id}',''),nullif(p_payload#>>'{variables,callrail_call_id}',''));
  v_phone := private.normalize_e164(coalesce(p_payload->>'from',p_payload->>'phone_number',p_payload#>>'{variables,callback_number}'));
  v_started := coalesce(nullif(p_payload->>'started_at','')::timestamptz,nullif(p_payload->>'created_at','')::timestamptz,now());
  if v_callrail_id is not null then select * into v_lead from public.leads where callrail_call_id=v_callrail_id order by received_at desc limit 1; end if;
  if v_lead.id is null and v_phone is not null then
    select * into v_lead from public.leads
    where source_system='callrail' and normalized_phone=v_phone and occurred_at between v_started-interval '30 minutes' and v_started+interval '30 minutes'
    order by abs(extract(epoch from (occurred_at-v_started))) limit 1;
  end if;
  if v_lead.id is not null then
    v_result := jsonb_set(v_result,'{metadata}',coalesce(v_result->'metadata','{}'::jsonb)||jsonb_build_object(
      'lead_public_id',v_lead.public_id,'lead_id',v_lead.id,'callrail_call_id',v_lead.callrail_call_id,'correlation_method',case when v_callrail_id is not null then 'callrail_call_id' else 'phone_time_window' end),true);
  end if;
  return v_result;
end;
$$;

