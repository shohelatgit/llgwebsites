create or replace function private.normalize_e164(p_value text)
returns text
language sql
immutable
strict
set search_path = pg_temp
as $$
  with normalized as (
    select btrim(p_value) as raw_value,
           regexp_replace(p_value, '[^0-9]', '', 'g') as digits
  )
  select case
    when raw_value ~ '^\+[1-9][0-9]{7,14}$' then raw_value
    when length(digits) = 10 then '+1' || digits
    when length(digits) between 8 and 15 and digits ~ '^[1-9]' then '+' || digits
    else null
  end
  from normalized;
$$;

revoke all on function private.normalize_e164(text) from public, anon, authenticated;

